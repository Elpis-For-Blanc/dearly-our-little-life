function t(speaker: 'first' | 'second', emotion: string, tags: string[], formal: string, casual: string): DefaultDialogueTurn {
  return { speaker, emotion, tags, text: { formal, casual } }
}

function b(id: string, categoryId: string, relationshipTypes: RelationshipType[] | undefined, ...turns: DefaultDialogueTurn[]): DefaultDialogueBundleDef {
  return relationshipTypes ? { id, categoryId, relationshipTypes, turns } : { id, categoryId, turns }
}

