import type { DefaultDialogueBundleDef, DefaultDialogueTurn } from './defaultDialogueLibrary'
import type { RelationshipType } from './relationshipConfig'

/**
 * Relationship-specific default conversations (static data merged into
 * `DEFAULT_DIALOGUE_BUNDLES`; never copied into a user's saved data).
 *
 *   neutral-XX  30  no `relationshipTypes` — usable by every pair, and the ONLY
 *                   default content a pair whose relationship was never chosen gets
 *   friend-XX   30  `['friend']`
 *   close-XX    30  `['close']`   (친밀한 관계 — the "절친" flavor)
 *
 * Families, rivals, awkward pairs and the extra 연인/부부 bundles follow in later
 * batches. Filtering is by relationship id (`relationshipTypes`) plus whether the
 * pair's relationship was actually chosen — never by wording.
 *
 * Authoring rules: each bundle is one connected 2-4 turn exchange; both the
 * 존댓말 and 반말 text of every turn is hand-written (never a suffix added to the
 * other); no forms of address, nicknames, kinship or rank terms; no invented
 * past events, ages, jobs or family; no claim that something unimplemented
 * (cooking, sleeping, work, buying) happened — only the moment, the time of day,
 * the room and feelings, with meals/rest only ever asked about or proposed;
 * nothing romantic. Personality reads through each turn's `emotion`/`tags`
 * (`lineAffinity`) and text length.
 */

