import type { DefaultDialogueBundleDef, DefaultDialogueTurn } from './defaultDialogueLibrary'
import type { RelationshipType } from './relationshipConfig'

/**
 * Affection bundles for the two romantic relationship types, kept as static
 * data (never copied into user saves) and merged into
 * `DEFAULT_DIALOGUE_BUNDLES`. Three groups, told apart by id prefix *and* by
 * `relationshipTypes` (the engine filters on the latter, the tests check the
 * two agree):
 *   - `love-XX`   70 bundles (01-40 original + 41-70 batch 2), `['romantic']`   — 연인 only
 *   - `spouse-XX` 70 bundles (01-40 original + 41-70 batch 2), `['married']`    — 부부 only
 *   - `affection-XX` 20 bundles, both          — 연인·부부 공용
 *
 * Batch 2 (love-41..70 / spouse-41..70) keeps the same authoring rules and
 * adds no new relationship id or storage shape — see romance.test.tsx for the
 * updated counts. 연인 batch 2 leans into 설렘/보고 싶은 마음/다정한 장난/칭찬 per
 * the spec; 부부 batch 2 leans into 익숙한 다정함/서로 챙기기/편안한 애정 표현/함께하는
 * 일상의 행복 — neither assumes a marriage length, children, or any other
 * unset fact (checked by the same forbidden-word test as batch 1).
 *
 * Authoring rules: every bundle is one connected 2-4 turn exchange; both the
 * 존댓말 and 반말 text of every turn is hand-written; no nicknames or terms of
 * address (여보/자기/당신 …) since the user's own 호칭 setting isn't read here;
 * no invented marriage length, children, jobs or shared history; no claim of
 * an action the simulation doesn't perform (sitting, cooking, sleeping, going
 * out) — only talk about the moment, the time of day and feelings.
 * Personality reads through each turn's `emotion`/`tags` (`lineAffinity` in
 * personalityTags.ts) and through text length (short turns suit 무뚝뚝함/과묵함).
 *
 * **Tone audit (found via user report, fixed at the root, not patched
 * around)**: `spouse-49`'s reply line used to read as a mocking retort
 * ("그렇게 잘 아는 척은 여전하네요" — "still pretending to know so well, as
 * usual") despite being tagged identically (`emotion: 'playful'`, `tags: PL`)
 * to every other warm teasing turn in this file — the engine has no way to
 * tell affectionate teasing apart from a cold one by metadata alone, only by
 * the actual words, so this had to be a content fix, not a weighting one.
 * Rewritten to land the same "우리는 서로를 잘 안다" beat without the jab. A
 * grep across every relationship-flavored dialogue file (romance +
 * relationshipDialogueLibrary.ts) for this and related dismissive/testing/
 * passive-aggressive patterns found no other occurrence — see
 * `romance.test.tsx`'s own "부부 대화는 비꼬거나 냉소적으로 들리지 않는다" describe
 * block, which turns that audit into a standing, reusable regression test
 * (scans every bundle reachable by a *warm* relationship type, not just
 * spouse-*, and separately simulates many real `married`-pair generations)
 * rather than leaving this as a one-off manual check.
 */

