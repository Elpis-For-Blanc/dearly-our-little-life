function t(speaker: 'first' | 'second', emotion: string, tags: string[], formal: string, casual: string): DefaultDialogueTurn {
  return { speaker, emotion, tags, text: { formal, casual } }
}

function b(id: string, categoryId: string, relationshipTypes: RelationshipType[], ...turns: DefaultDialogueTurn[]): DefaultDialogueBundleDef {
  return { id, categoryId, relationshipTypes, romantic: true, turns }
}

